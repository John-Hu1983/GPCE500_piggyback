// 1. Interrupts must be declared in address 0x8000~0xffff.
// 2. For FIQ, IRQ1 ~ IRQ7, user needs to clear P_INT_Clear before 
//    exiting interrupt routine
// 3. 
// 	_FIQ:	FIQ								// Fast interrupt entry
//  _IRQ0:	TimerA							// interrupt entry
//  _IRQ1:	TimerB							// interrupt entry
//  _IRQ2:	TimerC							// interrupt entry
//  _IRQ3:	DMA1, DMA2, ADC, SPI1, SPI2		// interrupt entry
//  _IRQ4:	KEY								// interrupt entry
//  _IRQ5:	SPU, EXT1, EXT2					// interrupt entry
//  _IRQ6:	CTS, 512Hz, 2KHz, 4KHz			// interrupt entry     
//  _IRQ7:	UART, 2Hz, 16Hz, 64Hz			// interrupt entry
//  _Break: Software interrupt              // interrupt entry
//==========================================================================

//**************************************************************************
// Header File Included Area
//**************************************************************************
.include GPCE36_CE5.inc

//**************************************************************************
// Contant Defintion Area
//**************************************************************************


//**************************************************************************
// Variable Publication Area
//**************************************************************************

//**************************************************************************
// Function Call Publication Area
//**************************************************************************
.public _BREAK;

.public _FIQ;

.public _IRQ0;

.public _IRQ1;

.public _IRQ2;

.public _IRQ3;

.public _IRQ4;

.public _IRQ5;

.public _IRQ6;

.public _IRQ7;


//**************************************************************************
// External Variable Declaration
//**************************************************************************


//**************************************************************************
// External Function Declaration
//**************************************************************************

//**************************************************************************
// RAM Definition Area
//**************************************************************************
.RAM


//**************************************************************************
// CODE Definition Area
//**************************************************************************
.TEXT

_BREAK:
	push R1, R5 to [SP]
	
	
	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _FIQ
//****************************************************************
_FIQ:
	push R1, R5 to [SP]

	
	pop R1, R5 from [SP]
	reti;
	
//****************************************************************
// _IRQ0
//****************************************************************
_IRQ0:
	push R1, R5 to [SP]
	
	
	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ1
//****************************************************************
_IRQ1:
	push R1, R5 to [SP]
	

	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ2
//****************************************************************
_IRQ2:
	push R1, R5 to [SP]


	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ3
//****************************************************************
_IRQ3:
	push R1, R5 to [SP]

		
	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ4
//****************************************************************
_IRQ4:
	push R1, R5 to [SP]
	
	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ5
//****************************************************************
_IRQ5:
	push R1, R5 to [SP]
	R1 = [P_SPU_INT_Status];
?L_SPU_Ch0:
	cmp R1, C_SPU_Ch0_INT_Flag;
	jne ?L_SPU_Ch1;
	
	R1 &= ~C_SPU_Ch0_En;
 	[P_SPU_CH_Ctrl] = R1;
 	
	R1 = C_SPU_Ch0_INT_Flag;
	[P_SPU_INT_Status] = R1;
	jmp ?L_Exit;
	
?L_SPU_Ch1:	
	cmp R1, C_SPU_Ch1_INT_Flag;
	jne ?L_SPU_Ch2;
	
 	R1 &= ~C_SPU_Ch1_En;
 	[P_SPU_CH_Ctrl] = R1;
	
	R1 = C_SPU_Ch1_INT_Flag;
	[P_SPU_INT_Status] = R1;
	jmp ?L_Exit;
	
?L_SPU_Ch2:
	//....
	
?L_Exit:	
	R1 = C_IRQ5_SPU;
	[P_INT_Status] = R1;
		pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ6
//****************************************************************
_IRQ6:
	push R1, R5 to [SP]
	
	pop R1, R5 from [SP]
	reti;

//****************************************************************
// _IRQ7
//****************************************************************
_IRQ7:
	push R1, R5 to [SP]
	
	pop R1, R5 from [SP]
	reti;


