/*
 *@ brief    : Look up the 16-bit PCM wave resource pointer for a given TONE_Wave_Id.
 *@ type     : public
 *@ argu in  : wave_id: TONE_Wave_Pulse, TONE_Wave_Piano, or TONE_Wave_Bell.
 *@ argu out : Pointer to the 0x8000-terminated 16-bit PCM wave array in ROM.
 *@ theme    : Wave resource table lookup for spu_play_tone().
 */
const unsigned *tone_get_wave_resource(TONE_Wave_Id wave_id)
{
    switch (wave_id)
    {
    case TONE_Wave_Piano:
        return tone_wave_piano;
    case TONE_Wave_Bell:
        return tone_wave_bell;
    case TONE_Wave_Pulse:
    default:
        return tone_wave_pulse;
    }
}
