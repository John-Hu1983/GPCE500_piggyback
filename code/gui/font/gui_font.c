/*
 *@ brief    : Return the proportional horizontal advance (ink width + kerning gap) for one char.
 *@ type     : private
 *@ argu in  : ch: ASCII character; size: GUI_Font_Size selector.
 *@ argu out : Horizontal pixel advance for ch.
 *@ theme    : Ensure uniform visual inter-character gap across narrow and wide letters.
 */
static u16 _font_get_char_advance(char ch, GUI_Font_Size size)
{
    u8 code = (u8)ch;

    if (code < 0x20U || code > 0x7FU)
    {
        code = 0x20U;
    }
    code = (u8)(code - 0x20U);

    switch (size)
    {
    case GUI_Font_6x8:
        return 6U;
    case GUI_Font_8x16:
        return (u16)(font_8x16_ink_w[code] + 1U);
    case GUI_Font_12x24:
        return (u16)(font_12x24_ink_w[code] + 2U);
    case GUI_Font_16x32:
        return (u16)((font_8x16_ink_w[code] + 1U) * 2U);
    case GUI_Font_24x48:
        return (u16)((font_12x24_ink_w[code] + 2U) * 2U);
    default:
        return (u16)(font_8x16_ink_w[code] + 1U);
    }
}

