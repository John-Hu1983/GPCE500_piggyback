/*
 *@ brief    : Calculate the exact proportional pixel width of a single-line string.
 *@ type     : public
 *@ argu in  : str: null-terminated string; size: GUI_Font_Size enum value.
 *@ argu out : Total pixel width from first ink column to last ink column.
 *@ theme    : Enables exact centered or right-aligned text positioning.
 */
u16 gui_font_get_str_width(const char *str, GUI_Font_Size size)
{
    u16 total_w = 0U;
    u16 gap = 0U;

    if (str == null)
    {
        return 0U;
    }

    switch (size)
    {
    case GUI_Font_6x8:
    case GUI_Font_8x16:
        gap = 1U;
        break;
    case GUI_Font_12x24:
    case GUI_Font_16x32:
        gap = 2U;
        break;
    case GUI_Font_24x48:
        gap = 4U;
        break;
    default:
        gap = 1U;
        break;
    }

    while (*str != '\0' && *str != '\n' && *str != '\r')
    {
        total_w = (u16)(total_w + _font_get_char_advance(*str++, size));
    }

    return (total_w > gap) ? (u16)(total_w - gap) : 0U;
}

/*
 *@ brief    : Render one proportional glyph from the crisp native 8x16 or 12x24 tables.
 *@ type     : private
 *@ argu in  : x, y: top-left coordinates; ch: ASCII char; fg_color, bg_color: RGB565 colors;
 *             has_bg: true for solid background; use_12x24: true for 12x24 base, false for 8x16;
 *             scale: 1 or 2 pixel multiplier.
 *@ argu out : Smooth glyph rendered to LCD with proportional cell width.
 *@ theme    : Fast window streaming when opaque, or horizontal span fills when transparent.
 */
static void _font_draw_crisp_char(s16 x, s16 y, char ch, u16 fg_color, u16 bg_color, bool has_bg,
                                  bool use_12x24, u8 scale)
{
    u8 code = (u8)ch;
    u8 ink_w, gap_cols, total_cols;
    u8 base_h = use_12x24 ? 24U : 16U;
    u16 cell_w, cell_h;
    u8 r, c, dy;

    if (code < 0x20U || code > 0x7FU)
    {
        code = 0x20U;
    }
    code = (u8)(code - 0x20U);

    ink_w = use_12x24 ? font_12x24_ink_w[code] : font_8x16_ink_w[code];
    gap_cols = use_12x24 ? 2U : 1U;
    total_cols = (u8)(ink_w + gap_cols);
    cell_w = (u16)(total_cols * scale);
    cell_h = (u16)(base_h * scale);

    if (has_bg && x >= 0 && y >= 0 && (u16)x + cell_w <= LCD_WIDTH && (u16)y + cell_h <= LCD_HEIGHT)
    {
        const LCD_Device *dev = lcd_get_device();
        lcd_set_window((u16)x, (u16)y, (u16)((u16)x + cell_w - 1U), (u16)((u16)y + cell_h - 1U));
        for (r = 0U; r < base_h; ++r)
        {
            u16 row_bits = use_12x24 ? FONT_12X24[code][r] : (u16)((u16)FONT_8X16[code][r] << 8);
            for (dy = 0U; dy < scale; ++dy)
            {
                for (c = 0U; c < ink_w; ++c)
                {
                    u16 px = ((row_bits & (u16)(0x8000U >> c)) != 0U) ? fg_color : bg_color;
                    dev->write_repeat_u16(px, scale);
                }
                dev->write_repeat_u16(bg_color, (u32)(gap_cols * scale));
            }
        }
        return;
    }

    if (has_bg)
    {
        gui_fill_rect(x, y, (s16)(x + (s16)cell_w - 1), (s16)(y + (s16)cell_h - 1), bg_color);
    }

    for (r = 0U; r < base_h; ++r)
    {
        u16 row_bits = use_12x24 ? FONT_12X24[code][r] : (u16)((u16)FONT_8X16[code][r] << 8);
        if (row_bits == 0U)
        {
            continue;
        }
        c = 0U;
        while (c < ink_w)
        {
            if ((row_bits & (u16)(0x8000U >> c)) != 0U)
            {
                u8 run_start = c;
                s16 px0, py0, px1, py1;
                while (c < ink_w && (row_bits & (u16)(0x8000U >> c)) != 0U)
                {
                    c++;
                }
                px0 = (s16)(x + (s16)(run_start * scale));
                py0 = (s16)(y + (s16)(r * scale));
                px1 = (s16)(x + (s16)(c * scale) - 1);
                py1 = (s16)(py0 + (s16)scale - 1);
                if (px0 == px1 && py0 == py1)
                {
                    gui_draw_point(px0, py0, fg_color);
                }
                else
                {
                    gui_fill_rect(px0, py0, px1, py1, fg_color);
                }
            }
            else
            {
                c++;
            }
        }
    }
}

/*
 *@ brief    : Draw one 5x8 character with arbitrary horizontal/vertical scaling.
 *@ type     : public
 *@ argu in  : x, y: top-left coordinates; ch: ASCII character; fg_color, bg_color: RGB565 colors;
 *             has_bg: true to fill background cell, false for transparent background;
 *             scale_x, scale_y: horizontal and vertical pixel multipliers (>= 1).
 *@ argu out : Character rendered to LCD.
 *@ theme    : Custom-scale renderer using 5x8 base table when non-preset scales are requested.
 */
void gui_draw_char_scaled(s16 x, s16 y, char ch, u16 fg_color, u16 bg_color, bool has_bg,
                          u8 scale_x, u8 scale_y)
{
    u8 code = (u8)ch;
    u8 col, row, dy;
    u8 col_bits;
    u16 cell_w, cell_h;

    if (scale_x == 0U || scale_y == 0U)
    {
        return;
    }
    if (code < gui_font_5x8.first_char || code > gui_font_5x8.last_char)
    {
        code = (u8)' ';
    }

    cell_w = (u16)((gui_font_5x8.width + gui_font_5x8.spacing_x) * scale_x);
    cell_h = (u16)(gui_font_5x8.height * scale_y);

    if (has_bg && x >= 0 && y >= 0 && (u16)x + cell_w <= LCD_WIDTH && (u16)y + cell_h <= LCD_HEIGHT)
    {
        const LCD_Device *dev = lcd_get_device();
        lcd_set_window((u16)x, (u16)y, (u16)((u16)x + cell_w - 1U), (u16)((u16)y + cell_h - 1U));
        for (row = 0U; row < gui_font_5x8.height; ++row)
        {
            for (dy = 0U; dy < scale_y; ++dy)
            {
                for (col = 0U; col < gui_font_5x8.width; ++col)
                {
                    u16 px;
                    col_bits = FONTS[code - gui_font_5x8.first_char][col];
                    px = ((col_bits & (u8)(1U << row)) != 0U) ? fg_color : bg_color;
                    dev->write_repeat_u16(px, scale_x);
                }
                dev->write_repeat_u16(bg_color, (u32)(gui_font_5x8.spacing_x * scale_x));
            }
        }
        return;
    }

    if (has_bg)
    {
        gui_fill_rect(x, y, (s16)(x + (s16)cell_w - 1), (s16)(y + (s16)cell_h - 1), bg_color);
    }

    for (col = 0U; col < gui_font_5x8.width; ++col)
    {
        col_bits = FONTS[code - gui_font_5x8.first_char][col];
        if (col_bits == 0U)
        {
            continue;
        }
        for (row = 0U; row < gui_font_5x8.height; ++row)
        {
            if ((col_bits & (u8)(1U << row)) != 0U)
            {
                s16 px_x = (s16)(x + (s16)(col * scale_x));
                s16 px_y = (s16)(y + (s16)(row * scale_y));
                if (scale_x == 1U && scale_y == 1U)
                {
                    gui_draw_point(px_x, px_y, fg_color);
                }
                else
                {
                    gui_fill_rect(px_x, px_y, (s16)(px_x + (s16)scale_x - 1),
                                  (s16)(px_y + (s16)scale_y - 1), fg_color);
                }
            }
        }
    }
}

/*
 *@ brief    : Draw a null-terminated string with arbitrary horizontal/vertical scaling and line wrap.
 *@ type     : public
 *@ argu in  : x, y: starting top-left coordinates; str: text string;
 *             fg_color, bg_color: RGB565 colors; has_bg: opaque if true;
 *             scale_x, scale_y: horizontal and vertical pixel multipliers.
 *@ argu out : String rendered with automatic line wrapping and '\n' support.
 *@ theme    : Custom-scale string renderer.
 */
void gui_draw_str_scaled(s16 x, s16 y, const char *str, u16 fg_color, u16 bg_color, bool has_bg,
                         u8 scale_x, u8 scale_y)
{
    s16 cur_x = x;
    s16 cur_y = y;
    s16 adv_x, adv_y;

    if (str == null || scale_x == 0U || scale_y == 0U)
    {
        return;
    }

    adv_x = (s16)((gui_font_5x8.width + gui_font_5x8.spacing_x) * scale_x);
    adv_y = (s16)((gui_font_5x8.height + gui_font_5x8.spacing_y) * scale_y);

    while (*str != '\0')
    {
        char ch = *str++;
        if (ch == '\r')
        {
            continue;
        }
        if (ch == '\n')
        {
            cur_x = x;
            cur_y = (s16)(cur_y + adv_y);
            continue;
        }
        if (cur_x + adv_x > (s16)LCD_WIDTH)
        {
            cur_x = x;
            cur_y = (s16)(cur_y + adv_y);
        }
        if (cur_y >= (s16)LCD_HEIGHT)
        {
            break;
        }
        gui_draw_char_scaled(cur_x, cur_y, ch, fg_color, bg_color, has_bg, scale_x, scale_y);
        cur_x = (s16)(cur_x + adv_x);
        system_clear_watchdog();
    }
}

/*
 *@ brief    : Internal dispatcher for preset GUI_Font_Size character rendering.
 *@ type     : private
 *@ argu in  : x, y: top-left coordinates; ch: ASCII char; fg_color, bg_color: RGB565;
 *             has_bg: opaque if true; size: GUI_Font_Size selector.
 *@ argu out : Character drawn using native crisp 8x16 or 12x24 tables (or 6x8 compact).
 *@ theme    : Dispatch to true high-resolution bitmap tables instead of blocky 5x8 scaling.
 */
static void _font_draw_preset_char(s16 x, s16 y, char ch, u16 fg_color, u16 bg_color, bool has_bg,
                                   GUI_Font_Size size)
{
    switch (size)
    {
    case GUI_Font_6x8:
        gui_draw_char_scaled(x, y, ch, fg_color, bg_color, has_bg, 1U, 1U);
        break;
    case GUI_Font_8x16:
        _font_draw_crisp_char(x, y, ch, fg_color, bg_color, has_bg, false, 1U);
        break;
    case GUI_Font_12x24:
        _font_draw_crisp_char(x, y, ch, fg_color, bg_color, has_bg, true, 1U);
        break;
    case GUI_Font_16x32:
        _font_draw_crisp_char(x, y, ch, fg_color, bg_color, has_bg, false, 2U);
        break;
    case GUI_Font_24x48:
        _font_draw_crisp_char(x, y, ch, fg_color, bg_color, has_bg, true, 2U);
        break;
    default:
        _font_draw_crisp_char(x, y, ch, fg_color, bg_color, has_bg, false, 1U);
        break;
    }
}

/*
 *@ brief    : Internal dispatcher for preset GUI_Font_Size string rendering with proportional kerning.
 *@ type     : private
 *@ argu in  : x, y: top-left coordinates; str: text string; fg_color, bg_color: RGB565;
 *             has_bg: opaque if true; size: GUI_Font_Size selector.
 *@ argu out : String drawn with even visual spacing between every pair of characters.
 *@ theme    : Advance cursor by each glyph's actual ink width + constant gap.
 */
static void _font_draw_preset_str(s16 x, s16 y, const char *str, u16 fg_color, u16 bg_color,
                                  bool has_bg, GUI_Font_Size size)
{
    s16 cur_x = x;
    s16 cur_y = y;
    s16 adv_y;

    if (str == null)
    {
        return;
    }

    adv_y = (s16)(gui_font_get_char_height(size) + 2U);

    while (*str != '\0')
    {
        char ch = *str++;
        s16 adv_x;
        if (ch == '\r')
        {
            continue;
        }
        if (ch == '\n')
        {
            cur_x = x;
            cur_y = (s16)(cur_y + adv_y);
            continue;
        }
        adv_x = (s16)_font_get_char_advance(ch, size);
        if (cur_x + adv_x > (s16)LCD_WIDTH)
        {
            cur_x = x;
            cur_y = (s16)(cur_y + adv_y);
        }
        if (cur_y >= (s16)LCD_HEIGHT)
        {
            break;
        }
        _font_draw_preset_char(cur_x, cur_y, ch, fg_color, bg_color, has_bg, size);
        cur_x = (s16)(cur_x + adv_x);
        system_clear_watchdog();
    }
}

